// Deterministic SIMULATED strategies for exercising the engine (simulation lab, demos, tests).
// Every record is marked source "simulated"; the scoring engine refuses to use them for real allocations.

import type { Strategy } from "./types.ts";

function rng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function gaussian(next: () => number) {
  const u = Math.max(next(), 1e-12), v = next();
  return Math.sqrt(-2 * Math.log(u)) * Math.cos(2 * Math.PI * v);
}

export const SAMPLE_PREFIX = "sim-";

/** Builds `days` daily points ending the day before `now`. */
export function simulatedStrategies(now: Date, days = 240): Strategy[] {
  const end = new Date(Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate() - 1));
  const dates = Array.from({ length: days }, (_, i) => new Date(end.getTime() - (days - 1 - i) * 86_400_000).toISOString().slice(0, 10));
  const r = rng(20261024);
  const market = dates.map(() => gaussian(r) * 0.025); // shared crypto factor
  const fx = dates.map(() => gaussian(r) * 0.003);
  const idio = () => dates.map(() => gaussian(r));
  const collectedAt = now.toISOString();
  const make = (id: string, providerId: string, name: string, assets: string[], style: string, maxLeverage: number, profitSharePct: number, minCopyUsd: number | null, returns: number[]): Strategy => ({
    id: SAMPLE_PREFIX + id,
    providerId,
    name: "SIM · " + name,
    externalId: "simulated",
    profileUrl: null,
    assets,
    style,
    maxLeverage,
    profitSharePct,
    minCopyUsd,
    series: { frequency: "daily", dates, returns: returns.map((x) => Math.round(Math.max(x, -0.95) * 1e6) / 1e6), basis: "gross", source: "simulated", collectedAt, verified: false },
    observations: [{ id: SAMPLE_PREFIX + id + "-obs", strategyId: SAMPLE_PREFIX + id, source: "simulated", method: "Generated by lib/engine/sample-data.ts", collectedAt, confidence: 0.2, verified: false, sourceUrl: null, values: { trades: Math.round(days * 0.8) } }],
    createdAt: collectedAt,
  });
  const e1 = idio(), e2 = idio(), e3 = idio(), e4 = idio(), e5 = idio(), e6 = idio();
  return [
    make("steady-btc", "btcc", "Steady BTC trend", ["BTC"], "trend", 5, 10, 10, market.map((m, i) => 0.0012 + 0.35 * m + 0.006 * e1[i])),
    make("btc-mirror", "bitget", "BTC mirror (correlated)", ["BTC"], "trend", 5, 10, 10, market.map((m, i) => 0.0010 + 0.35 * m + 0.002 * e2[i])),
    make("eth-swing", "btcc", "ETH swing", ["ETH"], "swing", 8, 12, 10, market.map((m, i) => 0.0008 + 0.15 * m + 0.010 * e3[i])),
    make("high-flyer", "bitget", "High-flyer 50x", ["SOL", "DOGE"], "momentum", 50, 15, 10, market.map((m, i) => 0.006 + 1.6 * m + 0.03 * e4[i] + (i === Math.floor(days * 0.7) ? -0.45 : 0))),
    make("fx-signal", "mt5", "EURUSD carry signal", ["EURUSD"], "carry", 10, 0, 50, fx.map((m, i) => 0.0004 + m + 0.001 * e5[i])),
    make("fading-star", "bitget", "Fading star", ["XRP"], "breakout", 10, 15, 10, market.map((m, i) => (i < days * 0.8 ? 0.003 : -0.004) + 0.2 * m + (i < days * 0.8 ? 0.008 : 0.025) * e6[i])),
  ];
}
