/** GEM Muse restricted deterministic proposal lab. Never execute arbitrary model output here. */
import {createHash} from "node:crypto";
import {mkdtemp,writeFile,rm} from "node:fs/promises";
import {tmpdir} from "node:os";
import {join} from "node:path";
import {execFile} from "node:child_process";
import {promisify} from "node:util";
import {validateMuseProposal} from "./muse-draft-pr-executor.mjs";
const run=promisify(execFile);
const REPO="gem-cybersecurity-monitoring-assist/btcc-copy-manager";
const UUID=/^[0-9a-f]{8}-[0-9a-f]{4}-4[0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;
const SECRET=/(github_pat_[A-Za-z0-9_]{12,}|gh[pousr]_[A-Za-z0-9_]{12,}|sk-[A-Za-z0-9_-]{15,}|-----BEGIN [^-]+ PRIVATE KEY-----)/i;
export function generateMuseProposal({repository,taskId,instruction,template="task-summary"}={}){
 if(repository!==REPO)throw Error("repository_not_allowed");
 if(!UUID.test(taskId||""))throw Error("invalid_task_id");
 if(typeof instruction!=="string"||instruction.trim().length<15||instruction.length>1200)throw Error("invalid_instruction");
 if(SECRET.test(instruction)||instruction.includes("\0"))throw Error("sensitive_instruction");
 if(template!=="task-summary")throw Error("template_not_approved");
 const id=taskId.toLowerCase(),request=instruction.trim().replace(/\s+/g," ");
 const content=[
  "/** Generated by GEM Muse deterministic proposal lab. Review before merging. */",
  "export const taskId = "+JSON.stringify(id)+";",
  "export const request = "+JSON.stringify(request)+";",
  "export function describeMuseTask() {",
  "  return Object.freeze({ taskId, request, codeChanges: false, status: \"proposal_only\" });",
  "}",
  ""
 ].join("\n");
 const proposal={repository:REPO,taskId:id,path:"scripts/muse-proposals/task-"+id.slice(0,8)+".mjs",content};
 return {proposal,plan:validateMuseProposal(proposal),generator:"deterministic_whitelist_v1",modelUsed:false};
}
export async function verifyMuseProposal(generated,{runner=run}={}){
 if(!generated?.proposal||generated.generator!=="deterministic_whitelist_v1"||generated.modelUsed!==false)throw Error("untrusted_generator");
 const {repository,taskId,path,content}=generated.proposal;
 const plan=validateMuseProposal({repository,taskId,path,content});
 if(plan.contentHash!==generated.plan?.contentHash)throw Error("content_hash_mismatch");
 if(path!=="scripts/muse-proposals/task-"+taskId.slice(0,8)+".mjs")throw Error("path_mismatch");
 const m=/^export const request = (.+);$/m.exec(content);
 if(!m)throw Error("unexpected_source_shape");
 let instruction;
 try{instruction=JSON.parse(m[1])}catch{throw Error("invalid_source_json")}
 if(generateMuseProposal({repository,taskId,instruction}).proposal.content!==content)throw Error("unexpected_source_shape");
 const dir=await mkdtemp(join(tmpdir(),"gem-muse-verify-"));
 try{
  const file=join(dir,"proposal.mjs");
  await writeFile(file,content,{mode:0o600});
  const opts={timeout:3500,maxBuffer:10000,env:{PATH:process.env.PATH||"/usr/bin:/bin",HOME:dir}};
  await runner(process.execPath,["--check",file],opts);
  const script="import {describeMuseTask,taskId} from "+JSON.stringify(file)+";const x=describeMuseTask();if(x.taskId!==taskId||x.status!=='proposal_only'||x.codeChanges!==false||!Object.isFrozen(x))process.exit(3);";
  await runner(process.execPath,["--input-type=module","-e",script],opts);
  return {verified:true,syntax:"passed",functional:"passed",isolatedTemp:true,sandboxedArbitraryCode:false,contentHash:plan.contentHash,modelUsed:false};
 }finally{await rm(dir,{recursive:true,force:true})}
}